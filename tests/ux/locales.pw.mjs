import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { startSite } from '../../tools/ux-site.mjs';
import { prepareContext } from './fixtures.mjs';

const pages = JSON.parse(await readFile(new URL('../../data/locales/pages.json', import.meta.url), 'utf8'));
const catalogue = JSON.parse(await readFile(new URL('../../data/links.json', import.meta.url), 'utf8'));
const companyBase = app => app.base.replace('dashboard.mrsoftware.dk', 'mrsoftware.dk');

test('every Danish public page loads with translated navigation and no horizontal overflow', async ({ page, context }) => {
  const app = await startSite();
  try {
    await prepareContext(context, app.base);
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    for (const entry of pages) {
      const response = await page.goto(new URL(entry.da, companyBase(app)).href);
      expect(response.status(), entry.da).toBe(200);
      await expect(page.locator('html')).toHaveAttribute('lang', 'da');
      await expect(page.getByRole('link', { name: 'English', exact: true })).toBeVisible();
      const heading = page.locator('h1');
      await expect(heading).toHaveCount(1);
      expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth), entry.da).toBeLessThanOrEqual(1);
      // Related cards are regenerated by JS, so test the rendered result as well as static HTML.
      for (const slot of await page.locator('[data-related-from]').all()) {
        const count = catalogue.links[await slot.getAttribute('data-related-from')]?.length ?? 0;
        await expect(slot.locator('a'), entry.da).toHaveCount(count);
        if (count) await expect(slot.locator('h2'), entry.da).not.toHaveText('See also');
      }
      for (const input of await page.locator('main input, main select, main textarea').all()) {
        expect(await input.evaluate(node => parseFloat(getComputedStyle(node).fontSize)), entry.da).toBeGreaterThanOrEqual(16);
      }
    }
    expect(errors).toEqual([]);
  } finally { await app.close(); }
});

