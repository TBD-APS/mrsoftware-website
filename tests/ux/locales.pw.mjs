test('Danish legal, case and error recovery links work without JavaScript', async ({ browser, page }, testInfo) => {
  const app = await startSite();
  const context = await browser.newContext({ javaScriptEnabled: false, viewport: page.viewportSize() });
  try {
    await prepareContext(context, app.base);
    const view = await context.newPage();
    await view.goto(companyBase(app) + 'da/');
    await view.locator('#solutions article[aria-labelledby="producey-title"] h3 a').click();
    await expect(view).toHaveURL(/\/da\/products\/producey\/$/);
    await expect(view.getByRole('heading', { name: 'Fra fabrikkens lager til afsendelse.' })).toBeVisible();
    await view.locator('.footer-legal a[href="/da/privacy-policy/"]').click();
    await expect(view).toHaveURL(/\/da\/privacy-policy\/$/);
    await expect(view.locator('html')).toHaveAttribute('lang', 'da');
    const response = await view.goto(companyBase(app) + 'da/denne-side-findes-ikke/');
    expect(response.status()).toBe(404);
    await expect(view.locator('html')).toHaveAttribute('lang', 'da');
    await expect(view.locator('h1')).toHaveText('Denne side findes ikke på hjemmesiden.');
    await testInfo.attach(`danish-recovery-${testInfo.project.name}`, { body: await view.screenshot(), contentType: 'image/png' });
    await view.locator('.hero-actions a[href="/da/"]').click();
    await expect(view).toHaveURL(new URL('/da/', companyBase(app)).href);
  } finally { await context.close(); await app.close(); }
});

test('Danish report downloads serve the reviewed localized bytes in every format', async ({ page, context }) => {
  const { createHash } = await import('node:crypto');
  const app = await startSite();
  try {
    // Browser downloads require a real response stream, as in the English report journey.
    const base = app.base.replace('dashboard.mrsoftware.dk', '127.0.0.1');
    await context.route('**/*', route => new URL(route.request().url()).origin === new URL(base).origin ? route.continue() : route.abort());
    await page.goto(base + 'da/roadmap/report/');
    const receipt = JSON.parse(await readFile(new URL('../../da/roadmap/report/export-receipt.json', import.meta.url), 'utf8'));
    for (const file of ['roadmap.pdf', 'roadmap.docx', 'roadmap.xlsx', 'roadmap.pptx', 'roadmap.csv', 'roadmap.html', 'developed-by-package.svg', 'pipeline-by-package.svg']) {
      const [download] = await Promise.all([
        page.waitForEvent('download'),
        page.locator(`a[href="/da/roadmap/report/${file}"]`).click(),
      ]);
      expect(download.suggestedFilename()).toBe(file);
      const bytes = await readFile(await download.path());
      expect(createHash('sha256').update(bytes).digest('hex'), file).toBe(receipt.files[file].sha256);
      if (file.endsWith('.pdf')) expect(bytes.subarray(0, 5).toString()).toBe('%PDF-');
    }
  } finally { await app.close(); }
});
